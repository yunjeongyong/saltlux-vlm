def n(v,d=4): return "-" if v is None else f"{v:.{d}f}"
def p(v): return "-" if v is None else f"{v:.1f}%"

def self_table():
    L=["| 실험 | CER↓ | TEDS↑ | 완전일치↑ | 반복루프 | 표 실패 | 요지 |","|---|---|---|---|---|---|---|"]
    for m,c,t,e,lp,tf,nt in F.SELF:
        b=lambda s: f"**{s}**" if m in ("exp_004","exp_011") else s
        L.append(f"| {b(m)} | {b(n(c))} | {b(n(t))} | {b(p(e))} | {'-' if lp is None else (f'**{lp}**' if lp==7 else lp)} | {'-' if tf is None else tf} | {nt or ''} |")
    L.append(f"| **1차 목표** | **{F.GOAL[0]}** | **{F.GOAL[1]}** | **{F.GOAL[2]}** | | | |")
    return "\n".join(L)

def ss_table():
    L=["| 구성 | 파이프라인 | total | general | table | 행수불일치 | 측정 배치 |","|---|---|---|---|---|---|---|"]
    for nm,pl,tot,gen,tbl,mm,*rest in F.SS:
        bt=rest[4]
        b=lambda s: f"**{s}**" if "alt/high" in nm else s
        L.append(f"| {b(nm)} | {pl} | {b(n(tot,3))} | {n(gen,3)} | {b(n(tbl,3))} | {'-' if mm is None else mm} | {F.BATCH.get(bt,'-')} |")
    return "\n".join(L)

def ss_domain():
    L=["| 구성 | 영수증 | 견적서 | 계산서 | 명세서 |","|---|---|---|---|---|"]
    for nm,pl,tot,gen,tbl,mm,rc,qu,iv,bl,bt,nt in F.SS:
        if rc is None: continue
        L.append(f"| {nm} | {n(rc,3)} | {n(qu,3)} | {n(iv,3)} | {n(bl,3)} |")
    return "\n".join(L)

def mix_table():
    L=["| 도메인 | General 필드 | "+" | ".join(F.CATS)+" | 데이터로 해결 |",
       "|---|---|"+"---|"*6]
    for d,cnt,a,b,c,dd,e,nt in F.DOMAIN_MIX:
        L.append(f"| {d} | {cnt:,} | {a}% | {b}% | {c}% | {dd}% | {e}% | **{c+e:.1f}%** |")
    return "\n".join(L)

def field_table(dom):
    L=["| 실패 필드 | 오답 | 표기차이 | 과다추출 | 의미동등 | 실제오독 | 해결 |","|---|---|---|---|---|---|---|"]
    for d,fld,w,a,b,c,e,real,act,solv in F.FIELDS:
        if d!=dom: continue
        L.append(f"| `{fld}` | {w} | {a} | {b} | {c} | {e} | {'**데이터**' if solv else '규칙'} |")
    return "\n".join(L)

def factor_table():
    L=["| 실험 | 크롭 | 페이지 반복 | CER | TEDS |","|---|---|---|---|---|"]
    for e,cp,rep,cer,teds in F.FACTOR:
        b=lambda s: f"**{s}**" if e=="exp_011" else s
        L.append(f"| {b(e)} | {b(f'{cp:,}')} | {rep} | {n(cer)} | {b(n(teds))} |")
    return "\n".join(L)

def role_table():
    L=["| 구분 | 언제 사용 | 목적 | 해당 데이터 |","|---|---|---|---|"]
    for a,b,c,d in F.DATA_ROLE: L.append(f"| {a} | {b} | {c} | {d} |")
    return "\n".join(L)

def val4_table():
    L=["| 도메인 | 행수 | 구성 |","|---|---|---|"]
    for a,b,c in F.VAL4: L.append(f"| {a} | {b} | {c} |")
    return "\n".join(L)

def exp(eid):
    return {x[0]:x for x in F.EXPS}[eid]

